import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
try{
 const desktop=await browser.newContext({viewport:{width:1440,height:900}});
 const page=await desktop.newPage();
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 page.on('dialog',d=>{void d.accept(d.type()==='prompt'?'Cliente smoke':undefined).catch(e=>{if(!/closed|Target page/i.test(e.message))console.warn(e.message)})});
 await page.goto('http://127.0.0.1:8080/index.html',{waitUntil:'networkidle'});
 await page.locator('.timeline-node').first().waitFor();
 assert.equal(await page.locator('.timeline-node').count(),6);
 assert.equal(await page.locator('.timeline-stage:visible').count(),1,'Erros no navegador: '+errors.join(' | ')+'; passo ativo: '+await page.locator('.timeline-node[aria-current="step"]').count());
 assert.equal(await page.locator('#timelineCount').innerText(),'Etapa 1 de 6');
 await page.locator('#name').fill('Suporte 3D');
 await page.locator('#quoteClient').fill('Cliente smoke');
 await page.locator('#timeline-stage-0 [data-timeline-go]').click();
 assert.equal(await page.locator('#timelineCount').innerText(),'Etapa 2 de 6');

 await page.locator('#slicerFile').setInputFiles({name:'test.gcode',mimeType:'text/plain',buffer:Buffer.from(';TIME:5400\n; filament used [g] = 32.5\nG1 X100')});
 await page.locator('#slicerPreview').waitFor({state:'visible'});
 await page.locator('#slicerApply').click();
 await page.locator('#slicerPasteDetails summary').click();
 await page.locator('#slicerPasteText').fill(['GrabCAD Print','Model Material: 40 g','Support Material: 10 g','Build Time: 4h 20m'].join(String.fromCharCode(10)));
 await page.locator('#slicerParsePaste').click();
 await page.locator('#slicerPreview').waitFor({state:'visible'});
 await page.locator('#slicerPieces').fill('2');
 await page.locator('#slicerApply').click();
 await page.locator('#timeline-stage-1 [data-timeline-go]').click();
 assert.equal(await page.locator('#grams').inputValue(),'20');
 assert.equal(await page.locator('#quantity').inputValue(),'2');
 assert.equal(await page.locator('#hours').inputValue(),'4');
 assert.equal(await page.locator('#minutes').inputValue(),'20');
 await page.locator('#timeline-stage-2 [data-timeline-go]').click();
 await page.locator('#supportPriceKg').fill('300');
 await page.waitForFunction(()=>document.getElementById('save')?.disabled===false);
 await page.locator('[data-mode="basic"]').click();
 assert.ok(await page.locator('body').evaluate(el=>el.classList.contains('basic-mode')));
 await page.locator('[data-mode="advanced"]').click();
 await page.locator('#timeline-stage-3 [data-timeline-go]').click();
 await page.locator('#suggested').waitFor({state:'visible'});
 let first=await page.locator('#suggested').innerText();
 assert.ok(first.includes('R$'),first);
 await page.locator('#margin').fill('35');
 const changed=await page.locator('#suggested').innerText();
 assert.notEqual(first,changed,'margem deve alterar o preço');
 assert.ok(await page.locator('#channelComparison').isVisible());
 assert.ok(await page.locator('#lotComparison').isVisible());
 await page.locator('[data-timeline-step="0"]').click();
 assert.equal(await page.locator('#name').inputValue(),'Suporte 3D');
 await page.locator('[data-timeline-step="5"]').click();
 assert.ok(await page.locator('#timelineFinalPrice').isVisible());
 assert.ok((await page.locator('#timelineFinalPrice').innerText()).includes('R$'));
 await page.locator('#save').click();
 await page.locator('#createOrder').click();
 await page.locator('#ordersList .orders-table tbody tr').waitFor();
 assert.ok((await page.locator('#ordersList').innerText()).includes('Cliente smoke'));
 await page.locator('[data-order-status]').selectOption('DELIVERED');
 await page.locator('[data-order-payment]').selectOption('PAID');
 await page.locator('[data-view="dashboard"]').click();
 assert.equal((await page.locator('#dashOrders').innerText()).trim(),'1');
 assert.equal((await page.locator('#dashDelivered').innerText()).trim(),'1');
 await page.reload({waitUntil:'networkidle'});
 await page.locator('[data-view="dashboard"]').click();
 assert.equal((await page.locator('#dashOrders').innerText()).trim(),'1');
 await page.locator('[data-view="calculator"]').click();
 assert.equal(await page.locator('#timelineCount').innerText(),'Etapa 6 de 6');
 await page.locator('[data-view="history"]').click();
 await page.locator('[data-load]').first().click();
 assert.equal(await page.locator('#timelineCount').innerText(),'Etapa 5 de 6');
 await page.locator('[data-view="profiles"]').click();
 await page.locator('#printerList [data-edit]').first().click();
 await page.locator('#printerForm [name="price"]').fill('2100');
 await page.locator('#savePrinterProfile').click();
 const profileText=(await page.locator('#printerList').innerText()).replace(/\u00a0/g,' ');
 assert.ok(profileText.includes('R$ 2.100,00'),'Perfil não atualizado: '+profileText);
 await page.locator('[data-view="calculator"]').click();
 await page.locator('#reset').click();
 assert.equal(await page.locator('#timelineCount').innerText(),'Etapa 1 de 6');

 const mobile=await browser.newContext({viewport:{width:390,height:844},isMobile:true,deviceScaleFactor:1});
 const m=await mobile.newPage();m.on('pageerror',e=>errors.push(e.message));
 await m.goto('http://127.0.0.1:8080/index.html',{waitUntil:'networkidle'});
 assert.ok(await m.locator('.project-timeline').isVisible());
 await m.locator('[data-timeline-step="4"]').click();
 assert.ok(await m.locator('#suggested').isVisible());
 const overflow=await m.evaluate(()=>({scroll:document.documentElement.scrollWidth,viewport:window.innerWidth}));
 assert.ok(overflow.scroll<=overflow.viewport+2,'overflow horizontal: '+JSON.stringify(overflow));
 await mobile.close();
 assert.deepEqual(errors,[],'Browser pageerrors');
 console.log('Browser smoke OK: timeline, imports, forms, prices, PDFs, orders, history, reload, mobile.');
 await desktop.close();
}finally{await browser.close()}
