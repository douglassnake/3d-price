import test from 'node:test';
import assert from 'node:assert/strict';
import {parseGcode,parseGrabCADReport,parseSlicerImport,parseCSV,parseDuration} from '../src/slicerAdapters.js';
import {calculate} from '../src/calculator.js';

const base={grams:20,quantity:1,hours:2,minutes:0,spoolPrice:100,spoolGrams:1000,watts:100,kwh:1,machinePrice:1000,lifeHours:1000,maintenance:0,consumables:0,packaging:0,failure:0,laborHours:0,laborRate:0,other:0,margin:20,marketplace:0,payment:0,taxes:0,discount:0,shipping:0};

test('Cura: tempo em segundos e metragem não convertida em gramas',()=>{
 const r=parseGcode(';Generated with Cura_SteamEngine\n;TIME:6300\n;Filament used: 3.4m');
 assert.equal(r.slicer,'Ultimaker Cura');assert.equal(r.seconds,6300);assert.equal(r.grams,null);
});
test('PrusaSlicer: massa e tempo com unidade',()=>{
 const r=parseGcode('; generated by PrusaSlicer\n; filament used [g] = 32.5\n; estimated printing time (normal mode) = 1h 25m 30s');
 assert.equal(r.slicer,'PrusaSlicer');assert.equal(r.grams,32.5);assert.equal(r.seconds,5130);
});
test('OrcaSlicer: prioriza massa total sem contá-la duas vezes',()=>{
 const r=parseGcode('; OrcaSlicer\n; filament used [g] = 5.25\n; total filament used [g] = 42.94\n; estimated printing time (normal mode) = 23m 46s');
 assert.equal(r.slicer,'OrcaSlicer');assert.equal(r.grams,42.94);assert.equal(r.seconds,1426);
});
test('Bambu Studio: reconhece dados e preserva alerta de suporte',()=>{
 const r=parseGcode('; BambuStudio\n; total filament used [g] = 40.1\n; support filament used [g] = 7.2\n; estimated printing time (normal mode) = 2h 3m 5s');
 assert.equal(r.slicer,'Bambu Studio');assert.equal(r.grams,40.1);assert.equal(r.supportGrams,7.2);assert.ok(r.warnings.some(x=>x.includes('suporte')));
});
test('GrabCAD Print Pro: relatório CSV separa modelo e suporte',()=>{
 const csv='Part,Quantity,Model Material (g),Support Material (g),Build Time\nA,2,49.5,11.2,4h 10m';
 const r=parseSlicerImport(csv,{format:'grabcad',fileName:'Build Report.csv'});
 assert.equal(r.slicer,'GrabCAD Print');assert.equal(r.grams,60.7);assert.equal(r.modelGrams,49.5);assert.equal(r.supportGrams,11.2);assert.equal(r.quantity,2);assert.equal(r.seconds,15000);
});
test('GrabCAD Pro: total consolidado prevalece sobre linhas individuais',()=>{
 const csv='Part;Model Material (g);Support Material (g);Build Time\nPeça A;18,50;3,00;1h 20m\nPeça B;22,50;4,00;1h 20m\nTOTAL;41,00;7,00;2h 5m';
 const r=parseGrabCADReport(csv);
 assert.equal(r.modelGrams,41);assert.equal(r.supportGrams,7);assert.equal(r.seconds,7500);
});
test('GrabCAD Pro: sem total não soma tempos paralelos',()=>{
 const csv='Part,Model Material (g),Support Material (g),Build Time\nA,11,2,1h\nB,12,3,1h';
 const r=parseGrabCADReport(csv);
 assert.equal(r.modelGrams,23);assert.equal(r.supportGrams,5);assert.equal(r.seconds,null);
 assert.ok(r.warnings.some(x=>x.includes('não foi somado')));
});
test('GrabCAD Print Standard: aceita texto copiado da tela Estimate',()=>{
 const txt='GrabCAD Print\nModel Material: 25.5 g\nSupport Material: 3.2 g\nBuild Time: 3h 15m';
 const r=parseGrabCADReport(txt);
 assert.equal(r.modelGrams,25.5);assert.equal(r.supportGrams,3.2);assert.equal(r.seconds,11700);
});
test('GrabCAD: volume em cm³ não pode ser convertido em massa sem densidade',()=>{
 const r=parseGrabCADReport('GrabCAD Print\nModel Material: 12.3 cm3\nSupport Material: 5 cm3\nBuild Time: 2h');
 assert.equal(r.grams,null);assert.equal(r.seconds,7200);
 assert.ok(r.warnings.some(x=>x.includes('massa em gramas')));
 assert.equal(r.volumes.length,2);
});
test('Tempo HH:MM ambíguo rejeitado sem coluna de unidade',()=>{
 assert.equal(parseDuration('02:30'),null);
 assert.equal(parseDuration('02:30',{twoPart:'h:mm'}),9000);
 assert.equal(parseDuration('02:30:00'),9000);
});
test('CSV com aspas contém separadores sem criar colunas falsas',()=>{
 const rows=parseCSV('Part;Model Material (g)\n"A; B";12,3');
 assert.deepEqual(rows,[['Part','Model Material (g)'],['A; B','12,3']]);
});
test('precificação cobra suporte separado com preço informado',()=>{
 const without=calculate(base);const withSupport=calculate({...base,supportGrams:12,supportPriceKg:400});
 assert.ok(Math.abs(withSupport.cost-without.cost-4.8)<1e-8);
});
test('não subprecificar suporte de preço desconhecido',()=>{
 assert.throws(()=>calculate({...base,supportGrams:12,supportPriceKg:0}),/preço do material de suporte/);
});
test('compatibilidade: suporte ausente mantém valor anterior',()=>{
 const a=calculate(base),b=calculate({...base,supportGrams:0,supportPriceKg:0});
 assert.equal(a.suggested,b.suggested);
});
